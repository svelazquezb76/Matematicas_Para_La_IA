# ============================================================
# TEMA: ORTOGONALIDAD Y PROYECCIONES VECTORIALES
# ============================================================
# Objetivo:
# 1. Calcular el producto punto de dos vectores.
# 2. Determinar si son ortogonales.
# 3. Calcular la proyección de un vector sobre otro.
# 4. Verificar que la proyección sea correcta.


# ============================================================
# 1. IMPORTAR NUMPY
# ============================================================

# NumPy permite crear vectores y realizar operaciones
# matemáticas de álgebra lineal.
import numpy as np


# ============================================================
# 2. DEFINIR LOS VECTORES
# ============================================================

# Creamos el vector A.
A = np.array([2, 3], dtype=float)

# Creamos el vector B.
B = np.array([3, -2], dtype=float)

# Mostramos los vectores.
print("VECTOR A:", A)
print("VECTOR B:", B)


# ============================================================
# 3. COMPROBAR LA ORTOGONALIDAD
# ============================================================

# Calculamos el producto punto de A y B.
producto_punto = np.dot(A, B)

# Mostramos el producto punto.
print("\nPRODUCTO PUNTO:")
print("A · B =", producto_punto)

# Si el producto punto es cero, los vectores son ortogonales.
# np.isclose permite considerar pequeños errores numéricos.
if np.isclose(producto_punto, 0):
    print("Los vectores son ortogonales.")
else:
    print("Los vectores no son ortogonales.")


# ============================================================
# 4. DEFINIR VECTORES PARA CALCULAR UNA PROYECCIÓN
# ============================================================

# Creamos un vector que será proyectado.
U = np.array([4, 2], dtype=float)

# Creamos el vector sobre el cual proyectaremos U.
V = np.array([2, 0], dtype=float)

# Mostramos los vectores utilizados en la proyección.
print("\nVECTORES PARA LA PROYECCIÓN:")
print("Vector U:", U)
print("Vector V:", V)


# ============================================================
# 5. CALCULAR EL PRODUCTO PUNTO
# ============================================================

# Calculamos U · V.
producto_UV = np.dot(U, V)

# Mostramos el resultado.
print("\nPRODUCTO PUNTO U · V:")
print(producto_UV)


# ============================================================
# 6. CALCULAR LA MAGNITUD AL CUADRADO DE V
# ============================================================

# La fórmula de la proyección utiliza ||V||².
# El producto punto de V consigo mismo equivale a ||V||².
magnitud_V_cuadrado = np.dot(V, V)

print("\nMAGNITUD DE V AL CUADRADO:")
print(magnitud_V_cuadrado)


# ============================================================
# 7. CALCULAR LA PROYECCIÓN VECTORIAL
# ============================================================

# No podemos proyectar sobre el vector cero, porque el
# denominador de la fórmula sería igual a cero.
if np.isclose(magnitud_V_cuadrado, 0):
    print("Error: no se puede proyectar sobre el vector cero.")
else:
    # Aplicamos la fórmula:
    # proy_V(U) = ((U · V) / ||V||²) * V
    proyeccion = (producto_UV / magnitud_V_cuadrado) * V

    # Mostramos la proyección calculada.
    print("\nPROYECCIÓN VECTORIAL DE U SOBRE V:")
    print(proyeccion)

    # Para estos datos, el resultado esperado es [4, 0].

    # ========================================================
    # 8. CALCULAR EL COMPONENTE PERPENDICULAR
    # ========================================================

    # Restamos la proyección al vector original.
    # El resultado es la parte de U perpendicular a V.
    componente_perpendicular = U - proyeccion

    print("\nCOMPONENTE PERPENDICULAR:")
    print(componente_perpendicular)

    # Comprobamos que el componente perpendicular sea
    # ortogonal al vector V.
    comprobacion = np.dot(componente_perpendicular, V)

    print("\nCOMPROBACIÓN DE ORTOGONALIDAD:")
    print("(U - proyección) · V =", comprobacion)

    if np.isclose(comprobacion, 0):
        print("La componente perpendicular es ortogonal a V.")
    else:
        print("La componente perpendicular no es ortogonal a V.")


# ============================================================
# 9. RESUMEN
# ============================================================

print("\nCONCLUSIONES:")
print("1. Dos vectores no nulos son ortogonales si su producto")
print("   punto es cero.")
print("2. La proyección identifica la componente de un vector")
print("   en la dirección de otro.")
print("3. La diferencia entre el vector original y su proyección")
print("   es perpendicular al vector de proyección.")