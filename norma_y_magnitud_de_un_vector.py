# ============================================================
# TEMA: NORMA Y MAGNITUD DE UN VECTOR
# ============================================================
# Objetivo:
# Calcular la longitud de un vector mediante la norma
# euclidiana utilizando Python y NumPy.


# ============================================================
# 1. IMPORTAR LA LIBRERÍA
# ============================================================

# NumPy permite realizar operaciones matemáticas con vectores.
import numpy as np


# ============================================================
# 2. DEFINIR UN VECTOR EN DOS DIMENSIONES
# ============================================================

# Creamos un vector con dos componentes: 3 y 4.
vector_2d = np.array([3, 4])

# Mostramos el vector.
print("VECTOR EN DOS DIMENSIONES")
print("Vector:", vector_2d)


# ============================================================
# 3. CALCULAR SU NORMA EUCLIDIANA
# ============================================================

# np.linalg.norm() calcula la norma euclidiana por defecto
# para un vector numérico.
magnitud_2d = np.linalg.norm(vector_2d)

# Mostramos el resultado de la operación.
print("Magnitud del vector:", magnitud_2d)

# Comprobación matemática:
# Magnitud = raíz cuadrada de (3² + 4²)
# Magnitud = raíz cuadrada de (9 + 16)
# Magnitud = raíz cuadrada de 25 = 5


# ============================================================
# 4. DEFINIR UN VECTOR EN TRES DIMENSIONES
# ============================================================

# Creamos un vector con tres componentes: 2, 3 y 6.
vector_3d = np.array([2, 3, 6])

# Mostramos el vector.
print("\nVECTOR EN TRES DIMENSIONES")
print("Vector:", vector_3d)


# ============================================================
# 5. CALCULAR LA NORMA DEL VECTOR 3D
# ============================================================

# Calculamos la longitud del vector tridimensional.
magnitud_3d = np.linalg.norm(vector_3d)

# Mostramos el resultado.
print("Magnitud del vector:", magnitud_3d)

# Comprobación matemática:
# Magnitud = raíz cuadrada de (2² + 3² + 6²)
# Magnitud = raíz cuadrada de (4 + 9 + 36)
# Magnitud = raíz cuadrada de 49 = 7


# ============================================================
# 6. CALCULAR LA NORMA MANUALMENTE
# ============================================================

# Creamos otro vector para comprobar la fórmula.
vector = np.array([1, 2, 2])

# Elevamos cada componente al cuadrado y sumamos los valores.
suma_cuadrados = np.sum(vector ** 2)

# Calculamos la raíz cuadrada de la suma.
magnitud_manual = np.sqrt(suma_cuadrados)

# Calculamos la norma usando la función de NumPy.
magnitud_numpy = np.linalg.norm(vector)

# Mostramos ambos procedimientos para compararlos.
print("\nCOMPARACIÓN DE MÉTODOS")
print("Vector:", vector)
print("Suma de cuadrados:", suma_cuadrados)
print("Magnitud calculada manualmente:", magnitud_manual)
print("Magnitud con NumPy:", magnitud_numpy)


# ============================================================
# 7. CALCULAR LA NORMA DE UN VECTOR PERSONALIZADO
# ============================================================

# Modifica los valores de esta lista para probar otros vectores.
vector_personalizado = np.array([5, 12])

# Calculamos la magnitud del vector elegido.
magnitud_personalizada = np.linalg.norm(vector_personalizado)

# Mostramos el vector y su magnitud.
print("\nVECTOR PERSONALIZADO")
print("Vector:", vector_personalizado)
print("Magnitud:", magnitud_personalizada)


# ============================================================
# 8. CONCLUSIONES
# ============================================================

print("\nCONCLUSIONES")
print("1. La norma representa la longitud de un vector.")
print("2. La norma euclidiana se calcula con la raíz de")
print("   la suma de los cuadrados de sus componentes.")
print("3. La función np.linalg.norm() calcula esta magnitud.")
print("4. La norma de un vector cero es igual a cero.")