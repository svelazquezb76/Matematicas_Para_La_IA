# ============================================================
# TEMA: INDEPENDENCIA Y DEPENDENCIA LINEAL
# ============================================================
# Objetivo:
# Analizar conjuntos de vectores y determinar si son
# linealmente independientes o linealmente dependientes.


# ============================================================
# 1. IMPORTAR NUMPY
# ============================================================

# NumPy permite trabajar con vectores, matrices y operaciones
# de álgebra lineal.
import numpy as np


# ============================================================
# 2. DEFINIR UNA FUNCIÓN PARA ANALIZAR VECTORES
# ============================================================

def analizar_vectores(vectores):
    # Convertimos la lista de vectores en una matriz numérica.
    # Cada columna de la matriz representa un vector.
    matriz = np.column_stack(vectores)

    # Calculamos el rango de la matriz.
    # El rango indica cuántas columnas son linealmente
    # independientes entre sí.
    rango = np.linalg.matrix_rank(matriz)

    # Obtenemos el número total de vectores.
    cantidad_vectores = matriz.shape[1]

    # Mostramos la matriz y los resultados.
    print("Matriz formada por los vectores:")
    print(matriz)

    print("Número de vectores:", cantidad_vectores)
    print("Rango de la matriz:", rango)

    # Si el rango es igual al número de vectores,
    # todos los vectores son linealmente independientes.
    if rango == cantidad_vectores:
        print("Resultado: vectores linealmente independientes.")
    else:
        # Si el rango es menor que el número de vectores,
        # existe dependencia lineal.
        print("Resultado: vectores linealmente dependientes.")

    print("-" * 55)


# ============================================================
# 3. EJEMPLO DE INDEPENDENCIA LINEAL
# ============================================================

# Estos vectores apuntan en direcciones diferentes
# y ninguno puede expresarse como múltiplo del otro.
v1 = np.array([1, 0])
v2 = np.array([0, 1])

print("EJEMPLO 1: INDEPENDENCIA LINEAL")

# Analizamos el conjunto formado por v1 y v2.
analizar_vectores([v1, v2])


# ============================================================
# 4. EJEMPLO DE DEPENDENCIA LINEAL
# ============================================================

# El vector v4 es el doble de v3.
# Por lo tanto, ambos vectores son linealmente dependientes.
v3 = np.array([1, 2])
v4 = np.array([2, 4])

print("EJEMPLO 2: DEPENDENCIA LINEAL")

# Analizamos el conjunto formado por v3 y v4.
analizar_vectores([v3, v4])


# ============================================================
# 5. EJEMPLO CON TRES VECTORES EN DOS DIMENSIONES
# ============================================================

# En un espacio de dos dimensiones pueden existir como máximo
# dos vectores linealmente independientes.
#
# Por eso, cualquier conjunto de tres vectores de dos
# componentes será linealmente dependiente.
v5 = np.array([1, 0])
v6 = np.array([0, 1])
v7 = np.array([1, 1])

print("EJEMPLO 3: TRES VECTORES EN DOS DIMENSIONES")

# Analizamos los tres vectores.
analizar_vectores([v5, v6, v7])


# ============================================================
# 6. CONCLUSIONES
# ============================================================

print("CONCLUSIONES")
print("1. El rango permite analizar la independencia lineal.")
print("2. Si el rango es igual al número de vectores,")
print("   los vectores son linealmente independientes.")
print("3. Si el rango es menor que el número de vectores,")
print("   los vectores son linealmente dependientes.")
print("4. En un espacio de dimensión n, puede haber como máximo")
print("   n vectores linealmente independientes.")