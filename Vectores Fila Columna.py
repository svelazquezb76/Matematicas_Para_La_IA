# ============================================================
# TEMA: VECTORES FILA Y COLUMNA
# ============================================================
# Objetivo:
# Crear, identificar y representar vectores fila y columna
# utilizando Python y la biblioteca NumPy.

# Importamos NumPy para trabajar con arreglos numéricos.
import numpy as np

# ============================================================
# 1. CREAR UN VECTOR
# ============================================================

# Creamos un vector con tres componentes: 3, 5 y 7.
vector = np.array([3, 5, 7])

# Mostramos el vector original.
print("VECTOR ORIGINAL:")
print(vector)

# ============================================================
# 2. REPRESENTAR EL VECTOR COMO FILA
# ============================================================

# reshape(1, -1) organiza los tres componentes en una fila.
# El número 1 indica que queremos una sola fila.
# El valor -1 permite que NumPy calcule las columnas necesarias.
vector_fila = vector.reshape(1, -1)

# Mostramos el vector fila.
print("\nVECTOR FILA:")
print(vector_fila)

# shape devuelve las dimensiones: (filas, columnas).
print("Dimensiones del vector fila:", vector_fila.shape)

# ============================================================
# 3. REPRESENTAR EL VECTOR COMO COLUMNA
# ============================================================

# reshape(-1, 1) organiza los componentes en una columna.
# El valor -1 permite calcular automáticamente las filas.
# El número 1 indica que queremos una sola columna.
vector_columna = vector.reshape(-1, 1)

# Mostramos el vector columna.
print("\nVECTOR COLUMNA:")
print(vector_columna)

# Mostramos sus dimensiones: tres filas y una columna.
print("Dimensiones del vector columna:", vector_columna.shape)

# ============================================================
# 4. TRANSPONER UN VECTOR
# ============================================================

# La transpuesta intercambia filas por columnas.
# El atributo T convierte el vector fila en columna.
transpuesta = vector_fila.T

# Mostramos el resultado de la transposición.
print("\nTRANSPUESTA DEL VECTOR FILA:")
print(transpuesta)

# Comprobamos sus dimensiones.
print("Dimensiones de la transpuesta:", transpuesta.shape)

# ============================================================
# 5. COMPARAR LAS DIMENSIONES
# ============================================================

# Un vector fila tiene una fila y tres columnas.
# Un vector columna tiene tres filas y una columna.
print("\nCOMPARACIÓN:")
print("Vector fila:", vector_fila.shape)
print("Vector columna:", vector_columna.shape)

# ============================================================
# 6. MULTIPLICACIÓN DE UN VECTOR FILA POR UNO COLUMNA
# ============================================================

# Multiplicamos una matriz de dimensión (1, 3) por otra
# de dimensión (3, 1). Las dimensiones internas coinciden.
#
# El resultado es una matriz de dimensión (1, 1), cuyo valor
# corresponde a 3*3 + 5*5 + 7*7 = 83.

resultado = vector_fila @ vector_columna

# El operador @ realiza la multiplicación matricial.
print("\nPRODUCTO FILA POR COLUMNA:")
print(resultado)

# Mostramos las dimensiones del resultado.
print("Dimensiones del resultado:", resultado.shape)

# ============================================================
# 7. CONCLUSIONES
# ============================================================

print("\nCONCLUSIONES:")
print("1. El vector fila organiza sus componentes horizontalmente.")
print("2. El vector columna organiza sus componentes verticalmente.")
print("3. shape indica el número de filas y columnas.")
print("4. La transpuesta intercambia filas por columnas.")
print("5. El operador @ realiza multiplicación matricial.")