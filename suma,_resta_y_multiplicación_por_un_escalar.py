# ============================================================
# TEMA: SUMA, RESTA Y MULTIPLICACIÓN POR UN ESCALAR
# ============================================================
# Objetivo:
# Realizar operaciones básicas con vectores utilizando NumPy
# y comprender cómo se calculan sus componentes.


# ============================================================
# 1. IMPORTAR LA LIBRERÍA
# ============================================================

# NumPy permite crear vectores y realizar operaciones
# matemáticas de manera sencilla.
import numpy as np


# ============================================================
# 2. DEFINIR LOS VECTORES Y EL ESCALAR
# ============================================================

# Creamos el vector A con dos componentes.
A = np.array([2, 3])

# Creamos el vector B con dos componentes.
B = np.array([4, 5])

# Definimos el escalar k, que es un número real.
k = 3

# Mostramos los valores iniciales.
print("VECTORES Y ESCALAR")
print("Vector A:", A)
print("Vector B:", B)
print("Escalar k:", k)


# ============================================================
# 3. SUMA DE VECTORES
# ============================================================

# Sumamos las componentes correspondientes de A y B.
# NumPy realiza automáticamente la suma componente por componente.
suma = A + B

# Mostramos la operación y su resultado.
print("\nSUMA DE VECTORES")
print("A + B =", suma)

# Ejemplo matemático:
# A = [2, 3]
# B = [4, 5]
# A + B = [2+4, 3+5] = [6, 8]


# ============================================================
# 4. RESTA DE VECTORES
# ============================================================

# Restamos cada componente de B a la componente correspondiente
# de A, conservando el orden A - B.
resta = A - B

# Mostramos la operación y su resultado.
print("\nRESTA DE VECTORES")
print("A - B =", resta)

# Ejemplo matemático:
# A - B = [2-4, 3-5] = [-2, -2]


# ============================================================
# 5. MULTIPLICACIÓN DE UN VECTOR POR UN ESCALAR
# ============================================================

# Multiplicamos cada componente de A por el escalar k.
# Si k = 3, cada componente del vector se multiplica por 3.
multiplicacion = k * A

# Mostramos la operación y su resultado.
print("\nMULTIPLICACIÓN POR UN ESCALAR")
print("k * A =", multiplicacion)

# Ejemplo matemático:
# A = [2, 3]
# k = 3
# k * A = [3*2, 3*3] = [6, 9]


# ============================================================
# 6. MULTIPLICACIÓN POR UN ESCALAR NEGATIVO
# ============================================================

# Definimos un escalar negativo.
k_negativo = -2

# Multiplicamos el vector A por el escalar negativo.
resultado_negativo = k_negativo * A

# Mostramos el resultado.
print("\nMULTIPLICACIÓN POR UN ESCALAR NEGATIVO")
print("(-2) * A =", resultado_negativo)

# Ejemplo matemático:
# (-2) * [2, 3] = [-4, -6]
# Geométricamente, el vector cambia de sentido y su magnitud
# se multiplica por el valor absoluto del escalar.


# ============================================================
# 7. MULTIPLICACIÓN POR CERO
# ============================================================

# Multiplicamos el vector A por cero.
# Todas las componentes se convierten en cero.
resultado_cero = 0 * A

# Mostramos el resultado.
print("\nMULTIPLICACIÓN POR CERO")
print("0 * A =", resultado_cero)

# El resultado es el vector cero.


# ============================================================
# 8. COMPROBAR LAS DIMENSIONES
# ============================================================

# Para sumar o restar vectores, ambos deben tener la misma
# dimensión. Verificamos esta condición antes de operar.
print("\nDIMENSIONES")
print("Dimensión de A:", A.size)
print("Dimensión de B:", B.size)

if A.size == B.size:
    # Como tienen el mismo número de componentes,
    # podemos sumarlos y restarlos.
    print("A y B tienen la misma dimensión.")
else:
    # No es válido realizar estas operaciones componente
    # por componente si sus dimensiones son diferentes.
    print("A y B tienen dimensiones diferentes.")


# ============================================================
# 9. RESUMEN DE RESULTADOS
# ============================================================

print("\nRESUMEN")
print("A =", A)
print("B =", B)
print("A + B =", suma)
print("A - B =", resta)
print("3 * A =", multiplicacion)
print("-2 * A =", resultado_negativo)
print("0 * A =", resultado_cero)