# ============================================================
# TEMA: TIPOS DE MATRICES
# ============================================================
# Objetivo:
# Crear y reconocer matrices cuadradas, diagonales, identidad,
# triangulares, simétricas y nulas utilizando Python y NumPy.


# ============================================================
# 1. IMPORTAR NUMPY
# ============================================================

# NumPy permite crear matrices y realizar operaciones
# de álgebra lineal.
import numpy as np


# ============================================================
# 2. MATRIZ CUADRADA
# ============================================================

# Creamos una matriz de tres filas y tres columnas.
A = np.array([
    [2, 4, 1],
    [3, 5, 6],
    [7, 8, 9]
])

print("1. MATRIZ CUADRADA")
print(A)

# shape devuelve el número de filas y columnas.
print("Orden:", A.shape)

# Una matriz es cuadrada cuando tiene igual cantidad
# de filas y columnas.
es_cuadrada = A.shape[0] == A.shape[1]
print("¿Es cuadrada?", es_cuadrada)


# ============================================================
# 3. MATRIZ DIAGONAL
# ============================================================

# Creamos una matriz cuyos elementos fuera de la diagonal
# principal son cero.
D = np.array([
    [4, 0, 0],
    [0, 7, 0],
    [0, 0, 2]
])

print("\n2. MATRIZ DIAGONAL")
print(D)

# np.diag(np.diag(D)) construye una matriz que conserva
# los elementos de la diagonal y pone ceros en el resto.
es_diagonal = (
    D.shape[0] == D.shape[1]
    and np.array_equal(D, np.diag(np.diag(D)))
)

print("¿Es diagonal?", es_diagonal)


# ============================================================
# 4. MATRIZ IDENTIDAD
# ============================================================

# np.eye(3) crea una matriz identidad de orden 3.
I = np.eye(3, dtype=int)

print("\n3. MATRIZ IDENTIDAD")
print(I)

# Comprobamos si la matriz es una identidad de orden 3.
es_identidad = np.array_equal(I, np.eye(3))

print("¿Es identidad?", es_identidad)


# ============================================================
# 5. MATRIZ TRIANGULAR SUPERIOR
# ============================================================

# En esta matriz, todos los elementos debajo de la diagonal
# principal son cero.
U = np.array([
    [2, 4, 5],
    [0, 3, 6],
    [0, 0, 7]
])

print("\n4. MATRIZ TRIANGULAR SUPERIOR")
print(U)

# np.triu(U) conserva la diagonal y los elementos superiores.
es_triangular_superior = (
    U.shape[0] == U.shape[1]
    and np.array_equal(U, np.triu(U))
)

print("¿Es triangular superior?", es_triangular_superior)


# ============================================================
# 6. MATRIZ TRIANGULAR INFERIOR
# ============================================================

# En esta matriz, todos los elementos por encima de la
# diagonal principal son cero.
L = np.array([
    [2, 0, 0],
    [4, 3, 0],
    [5, 6, 7]
])

print("\n5. MATRIZ TRIANGULAR INFERIOR")
print(L)

# np.tril(L) conserva la diagonal y los elementos inferiores.
es_triangular_inferior = (
    L.shape[0] == L.shape[1]
    and np.array_equal(L, np.tril(L))
)

print("¿Es triangular inferior?", es_triangular_inferior)


# ============================================================
# 7. MATRIZ SIMÉTRICA
# ============================================================

# Una matriz simétrica es igual a su transpuesta.
S = np.array([
    [1, 2, 3],
    [2, 4, 5],
    [3, 5, 6]
])

print("\n6. MATRIZ SIMÉTRICA")
print(S)

# .T obtiene la transpuesta de la matriz.
print("Transpuesta de S:")
print(S.T)

# Comprobamos si la matriz es igual a su transpuesta.
es_simetrica = (
    S.shape[0] == S.shape[1]
    and np.array_equal(S, S.T)
)

print("¿Es simétrica?", es_simetrica)


# ============================================================
# 8. MATRIZ NULA
# ============================================================

# np.zeros((2, 3)) crea una matriz de dos filas y tres columnas
# en la que todos los elementos son cero.
N = np.zeros((2, 3), dtype=int)

print("\n7. MATRIZ NULA")
print(N)

# np.all(N == 0) verifica que todos los elementos sean cero.
es_nula = np.all(N == 0)

print("Orden:", N.shape)
print("¿Es nula?", es_nula)


# ============================================================
# 9. RESUMEN DE VERIFICACIONES
# ============================================================

print("\nRESUMEN")
print("Matriz A: cuadrada =", es_cuadrada)
print("Matriz D: diagonal =", es_diagonal)
print("Matriz I: identidad =", es_identidad)
print("Matriz U: triangular superior =", es_triangular_superior)
print("Matriz L: triangular inferior =", es_triangular_inferior)
print("Matriz S: simétrica =", es_simetrica)
print("Matriz N: nula =", es_nula)