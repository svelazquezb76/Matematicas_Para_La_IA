# ============================================================
# TEMA: DEFINICIÓN, ORDEN, FILAS Y COLUMNAS DE MATRICES
# ============================================================
# Objetivo:
# Crear una matriz, conocer su orden, identificar sus filas
# y columnas, y consultar sus elementos mediante índices.


# ============================================================
# 1. IMPORTAR NUMPY
# ============================================================

# NumPy permite crear matrices y realizar operaciones
# matemáticas con sus elementos.
import numpy as np


# ============================================================
# 2. DEFINIR UNA MATRIZ
# ============================================================

# Creamos una matriz de dos filas y tres columnas.
# Cada lista interna representa una fila de la matriz.
A = np.array([
    [2, 4, 6],
    [1, 3, 5]
])

# Mostramos la matriz completa.
print("MATRIZ A:")
print(A)


# ============================================================
# 3. IDENTIFICAR EL ORDEN DE LA MATRIZ
# ============================================================

# shape devuelve una tupla con el número de filas
# y el número de columnas, en ese orden.
orden = A.shape

# El primer valor de shape corresponde a las filas.
filas = A.shape[0]

# El segundo valor de shape corresponde a las columnas.
columnas = A.shape[1]

# Mostramos la información de la matriz.
print("\nORDEN DE LA MATRIZ")
print("Orden:", orden)
print("Número de filas:", filas)
print("Número de columnas:", columnas)


# ============================================================
# 4. CONTAR LOS ELEMENTOS DE LA MATRIZ
# ============================================================

# size indica el número total de elementos de la matriz.
cantidad_elementos = A.size

# Mostramos la cantidad de elementos.
print("\nTOTAL DE ELEMENTOS")
print("Número de elementos:", cantidad_elementos)

# Para esta matriz:
# 2 filas * 3 columnas = 6 elementos.


# ============================================================
# 5. ACCEDER A LOS ELEMENTOS DE LA MATRIZ
# ============================================================

# En Python, los índices comienzan en cero.
# Por eso, A[0, 0] representa la primera fila y primera columna.
print("\nACCESO A LOS ELEMENTOS")
print("Elemento de fila 1, columna 1:", A[0, 0])
print("Elemento de fila 1, columna 2:", A[0, 1])
print("Elemento de fila 2, columna 3:", A[1, 2])

# La notación matemática comienza habitualmente en 1,
# mientras que los índices de Python comienzan en 0.


# ============================================================
# 6. EXTRAER UNA FILA
# ============================================================

# A[0, :] selecciona la primera fila.
# Los dos puntos indican que se seleccionan todas las columnas.
primera_fila = A[0, :]

# Mostramos la fila seleccionada.
print("\nPRIMERA FILA")
print(primera_fila)

# A[1, :] selecciona la segunda fila.
segunda_fila = A[1, :]

print("SEGUNDA FILA")
print(segunda_fila)


# ============================================================
# 7. EXTRAER UNA COLUMNA
# ============================================================

# A[:, 0] selecciona la primera columna.
# Los dos puntos indican que se seleccionan todas las filas.
primera_columna = A[:, 0]

# Mostramos la columna seleccionada.
print("\nPRIMERA COLUMNA")
print(primera_columna)

# A[:, 1] selecciona la segunda columna.
segunda_columna = A[:, 1]

print("SEGUNDA COLUMNA")
print(segunda_columna)

# A[:, 2] selecciona la tercera columna.
tercera_columna = A[:, 2]

print("TERCERA COLUMNA")
print(tercera_columna)


# ============================================================
# 8. RECORRER TODOS LOS ELEMENTOS
# ============================================================

# Recorremos cada fila mediante su índice.
print("\nELEMENTOS POR FILA")

for i in range(A.shape[0]):
    # Recorremos cada columna de la fila actual.
    for j in range(A.shape[1]):
        # Mostramos el elemento y su posición.
        # Sumamos 1 a los índices para mostrarlos como
        # posiciones matemáticas, que comienzan en 1.
        print(
            f"Elemento de fila {i + 1}, "
            f"columna {j + 1}: {A[i, j]}"
        )


# ============================================================
# 9. CREAR UNA MATRIZ CUADRADA
# ============================================================

# Creamos una matriz con dos filas y dos columnas.
B = np.array([
    [1, 2],
    [3, 4]
])

# Mostramos la matriz y sus dimensiones.
print("\nMATRIZ CUADRADA B:")
print(B)
print("Orden de B:", B.shape)

# Comprobamos si tiene el mismo número de filas y columnas.
if B.shape[0] == B.shape[1]:
    print("B es una matriz cuadrada.")
else:
    print("B es una matriz rectangular.")


# ============================================================
# 10. CONCLUSIONES
# ============================================================

print("\nCONCLUSIONES")
print("1. Una matriz organiza elementos en filas y columnas.")
print("2. El orden se expresa como filas por columnas.")
print("3. shape permite conocer las dimensiones de una matriz.")
print("4. size devuelve el número total de elementos.")
print("5. Los índices de Python comienzan en cero.")