# ============================================================
# TEMA: DEFINICIÓN, COMPONENTES, DIMENSIÓN Y REPRESENTACIÓN
#       DE UN VECTOR
# ============================================================
# Objetivo:
# Comprender qué es un vector, identificar sus componentes,
# conocer su dimensión y representarlo gráficamente en 2D y 3D.
#
# Los vectores son importantes en Inteligencia Artificial porque
# permiten representar datos, características, coordenadas,
# imágenes y otros tipos de información numérica.


# ============================================================
# 1. IMPORTACIÓN DE LIBRERÍAS
# ============================================================

# NumPy permite trabajar con arreglos y operaciones matemáticas.
import numpy as np

# Matplotlib permite crear gráficas y representar vectores.
import matplotlib.pyplot as plt


# ============================================================
# 2. DEFINICIÓN DE UN VECTOR
# ============================================================

# Un vector es una colección ordenada de números llamados
# componentes. En este ejemplo, el vector tiene dos componentes.
#
# La primera componente representa la coordenada horizontal (x).
# La segunda componente representa la coordenada vertical (y).

vector = np.array([3, 2])

# Mostramos el vector en pantalla.
print("VECTOR")
print("El vector es:", vector)

# Mostramos cada componente por separado.
print("Primera componente (x):", vector[0])
print("Segunda componente (y):", vector[1])


# ============================================================
# 3. COMPONENTES Y DIMENSIÓN DEL VECTOR
# ============================================================

# La dimensión de un vector es la cantidad de componentes
# que contiene.
#
# En este caso, el vector [3, 2] tiene dos componentes,
# por lo tanto, pertenece a un espacio de dimensión 2.

dimension = vector.size

# Mostramos la dimensión del vector.
print("\nDIMENSIÓN DEL VECTOR")
print("Número de componentes:", dimension)

# Recorremos el vector para mostrar sus componentes.
print("\nCOMPONENTES DEL VECTOR")

for indice, componente in enumerate(vector):
    # enumerate() permite obtener el índice y el valor
    # de cada componente del vector.
    print(f"Componente {indice + 1}: {componente}")


# ============================================================
# 4. REPRESENTACIÓN GRÁFICA DE UN VECTOR EN 2D
# ============================================================

# Creamos una figura para dibujar el vector.
plt.figure(figsize=(7, 6))

# Dibujamos una flecha desde el origen (0, 0) hasta (3, 2).
# quiver() permite representar vectores mediante flechas.
plt.quiver(
    0, 0,                    # Coordenadas del punto de inicio.
    vector[0], vector[1],     # Componentes horizontal y vertical.
    angles="xy",              # Interpreta los datos como coordenadas.
    scale_units="xy",         # Utiliza las unidades de los ejes.
    scale=1,                  # Mantiene la magnitud de la flecha.
    color="blue"              # Color de la flecha.
)

# Marcamos el punto final del vector.
plt.scatter(vector[0], vector[1], color="red")

# Escribimos una etiqueta junto al punto final.
plt.text(
    vector[0] + 0.1,
    vector[1] + 0.1,
    f"({vector[0]}, {vector[1]})"
)

# Configuramos los límites de los ejes para visualizar el vector.
plt.xlim(-1, 5)
plt.ylim(-1, 4)

# Dibujamos los ejes horizontal y vertical.
plt.axhline(0, color="black", linewidth=0.8)
plt.axvline(0, color="black", linewidth=0.8)

# Agregamos cuadrícula para facilitar la lectura de coordenadas.
plt.grid(True)

# Indicamos el nombre de cada eje.
plt.xlabel("Eje X")
plt.ylabel("Eje Y")

# Agregamos título a la gráfica.
plt.title("Representación de un vector en dos dimensiones")

# Conservamos la misma escala en ambos ejes.
plt.axis("equal")

# Mostramos la gráfica.
plt.show()


# ============================================================
# 5. DEFINICIÓN Y REPRESENTACIÓN DE UN VECTOR EN 3D
# ============================================================

# Un vector tridimensional tiene tres componentes:
# x, y y z.
#
# El vector siguiente representa un punto con coordenadas
# (4, 2, 5) respecto al origen.

vector_3d = np.array([4, 2, 5])

# Mostramos el vector y su dimensión.
print("\nVECTOR EN TRES DIMENSIONES")
print("Vector:", vector_3d)
print("Número de componentes:", vector_3d.size)

# Importamos las herramientas necesarias para crear
# una gráfica tridimensional.
from mpl_toolkits.mplot3d import Axes3D

# Creamos una figura y un sistema de ejes 3D.
figura = plt.figure(figsize=(8, 6))
ejes = figura.add_subplot(111, projection="3d")

# Dibujamos una flecha desde el origen hasta (4, 2, 5).
ejes.quiver(
    0, 0, 0,                         # Punto de inicio.
    vector_3d[0],                    # Componente X.
    vector_3d[1],                    # Componente Y.
    vector_3d[2],                    # Componente Z.
    color="green",
    arrow_length_ratio=0.1           # Tamaño relativo de la punta.
)

# Marcamos el punto final del vector.
ejes.scatter(
    vector_3d[0],
    vector_3d[1],
    vector_3d[2],
    color="red",
    s=50
)

# Etiquetamos el punto final con sus coordenadas.
ejes.text(
    vector_3d[0],
    vector_3d[1],
    vector_3d[2],
    f"({vector_3d[0]}, {vector_3d[1]}, {vector_3d[2]})"
)

# Indicamos el nombre de los tres ejes.
ejes.set_xlabel("Eje X")
ejes.set_ylabel("Eje Y")
ejes.set_zlabel("Eje Z")

# Agregamos un título a la gráfica tridimensional.
ejes.set_title("Representación de un vector en tres dimensiones")

# Mostramos la gráfica.
plt.show()


# ============================================================
# 6. REPRESENTACIÓN DE UN VECTOR COMO COLUMNA
# ============================================================

# Un vector también puede representarse como una matriz columna.
#
# El método reshape(-1, 1) transforma el vector en una estructura
# con una columna y tantas filas como componentes tenga.
#
# Esta representación es útil en álgebra lineal y en operaciones
# matemáticas empleadas en Inteligencia Artificial.

vector_columna = vector.reshape(-1, 1)

# Mostramos el vector original y su versión como columna.
print("\nREPRESENTACIÓN COMO VECTOR COLUMNA")
print("Vector original:")
print(vector)

print("\nVector columna:")
print(vector_columna)


# ============================================================
# 7. COMPARACIÓN DE VECTORES CON DIFERENTES DIMENSIONES
# ============================================================

# Creamos tres vectores de ejemplo.
vector_2d = np.array([2, 4])          # Tiene 2 componentes.
vector_3d_ejemplo = np.array([2, 4, 6])  # Tiene 3 componentes.
vector_4d = np.array([2, 4, 6, 8])   # Tiene 4 componentes.

# Mostramos cada vector y su dimensión.
print("\nCOMPARACIÓN DE VECTORES")

print("Vector 2D:", vector_2d)
print("Dimensión:", vector_2d.size)

print("\nVector 3D:", vector_3d_ejemplo)
print("Dimensión:", vector_3d_ejemplo.size)

print("\nVector 4D:", vector_4d)
print("Dimensión:", vector_4d.size)

# Nota:
# Los vectores de dos y tres dimensiones se pueden representar
# directamente en gráficas 2D y 3D.
# Un vector de cuatro dimensiones no puede dibujarse directamente
# en un espacio geométrico tridimensional convencional, pero sí
# puede almacenarse y procesarse numéricamente.


