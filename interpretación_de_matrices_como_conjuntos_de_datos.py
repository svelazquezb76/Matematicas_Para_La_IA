import numpy as np

# 1. Crear una matriz de datos:
# Cada fila es un estudiante y cada columna una característica.
X = np.array([
    [5, 8, 90],
    [3, 6, 75],
    [7, 10, 95]
])

# 2. Consultar las dimensiones de la matriz.
print("Matriz de datos:")
print(X)

print("\nDimensiones:", X.shape)
print("Número de estudiantes:", X.shape[0])
print("Número de características:", X.shape[1])

# 3. Seleccionar una fila: primer estudiante.
print("\nDatos del primer estudiante:", X[0, :])

# 4. Seleccionar una columna: horas de estudio.
print("Horas de estudio:", X[:, 0])

# 5. Definir una matriz de pesos para dos salidas.
W = np.array([
    [0.2, 0.1],
    [0.3, 0.4],
    [0.5, 0.2]
])

# 6. Comprobar la compatibilidad antes de multiplicar.
if X.shape[1] == W.shape[0]:
    Y = X @ W
    print("\nDimensiones de W:", W.shape)
    print("Resultado X @ W:")
    print(Y)
    print("Dimensiones del resultado:", Y.shape)
else:
    print("Las dimensiones no son compatibles.")