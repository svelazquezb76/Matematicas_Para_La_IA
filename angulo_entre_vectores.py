# ============================================================
# TEMA: ÁNGULO ENTRE VECTORES
# ============================================================
# Objetivo:
# Calcular el ángulo entre dos vectores utilizando el producto
# punto, sus magnitudes y la función arccos.


# ============================================================
# 1. IMPORTAR NUMPY
# ============================================================

# NumPy permite realizar operaciones de álgebra lineal,
# calcular magnitudes y utilizar funciones trigonométricas.
import numpy as np


# ============================================================
# 2. DEFINIR LOS VECTORES
# ============================================================

# Creamos el vector A con dos componentes.
A = np.array([1, 0])

# Creamos el vector B con dos componentes.
B = np.array([0, 1])

# Mostramos los vectores que vamos a comparar.
print("VECTOR A:", A)
print("VECTOR B:", B)


# ============================================================
# 3. CALCULAR EL PRODUCTO PUNTO
# ============================================================

# El producto punto multiplica las componentes correspondientes
# y suma los resultados.
producto_punto = np.dot(A, B)

# Mostramos el producto punto obtenido.
print("\nPRODUCTO PUNTO")
print("A · B =", producto_punto)


# ============================================================
# 4. CALCULAR LAS MAGNITUDES
# ============================================================

# np.linalg.norm() calcula la magnitud o norma euclidiana
# de cada vector.
magnitud_A = np.linalg.norm(A)
magnitud_B = np.linalg.norm(B)

# Mostramos las magnitudes calculadas.
print("\nMAGNITUDES")
print("Magnitud de A:", magnitud_A)
print("Magnitud de B:", magnitud_B)


# ============================================================
# 5. CALCULAR EL COSENO DEL ÁNGULO
# ============================================================

# La fórmula del coseno del ángulo es:
# cos(theta) = (A · B) / (||A|| * ||B||)
#
# Primero comprobamos que ninguno de los vectores sea cero,
# porque no se puede dividir entre una magnitud igual a cero.

if magnitud_A == 0 or magnitud_B == 0:
    print("\nNo se puede calcular el ángulo.")
    print("Ambos vectores deben ser distintos del vector cero.")

else:
    # Calculamos el coseno del ángulo entre los vectores.
    coseno = producto_punto / (magnitud_A * magnitud_B)

    # np.clip limita el resultado al intervalo [-1, 1].
    # Esto evita errores numéricos pequeños al usar arccos.
    coseno = np.clip(coseno, -1.0, 1.0)

    # ========================================================
    # 6. CALCULAR EL ÁNGULO EN RADIANES Y GRADOS
    # ========================================================

    # np.arccos() calcula el ángulo en radianes a partir
    # del valor del coseno.
    angulo_radianes = np.arccos(coseno)

    # Convertimos el ángulo de radianes a grados.
    angulo_grados = np.degrees(angulo_radianes)

    # Mostramos todos los resultados.
    print("\nRESULTADOS")
    print("Coseno del ángulo:", coseno)
    print("Ángulo en radianes:", angulo_radianes)
    print("Ángulo en grados:", angulo_grados)

    # ========================================================
    # 7. INTERPRETAR EL ÁNGULO
    # ========================================================

    # Clasificamos el ángulo según su medida.
    if np.isclose(angulo_grados, 90.0):
        print("Interpretación: los vectores son perpendiculares.")
    elif np.isclose(angulo_grados, 0.0):
        print("Interpretación: tienen la misma dirección y sentido.")
    elif np.isclose(angulo_grados, 180.0):
        print("Interpretación: tienen sentidos opuestos.")
    elif angulo_grados < 90.0:
        print("Interpretación: el ángulo es agudo.")
    else:
        print("Interpretación: el ángulo es obtuso.")