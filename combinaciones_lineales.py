# ============================================================
# TEMA: COMBINACIONES LINEALES DE VECTORES
# ============================================================
# Objetivo:
# Calcular una combinación lineal mediante la multiplicación
# de vectores por escalares y la suma de los resultados.

# Importamos NumPy para trabajar con vectores numéricos.
import numpy as np


# ============================================================
# 1. DEFINIR LOS VECTORES
# ============================================================

# Creamos el vector u con dos componentes.
u = np.array([2, 3])

# Creamos el vector v con dos componentes.
v = np.array([4, 1])

# Mostramos los vectores originales.
print("VECTOR u:", u)
print("VECTOR v:", v)


# ============================================================
# 2. DEFINIR LOS ESCALARES
# ============================================================

# Los escalares indican cuánto contribuye cada vector
# a la combinación lineal.
a = 2
b = 3

# Mostramos los escalares.
print("\nESCALARES")
print("a =", a)
print("b =", b)


# ============================================================
# 3. MULTIPLICAR CADA VECTOR POR SU ESCALAR
# ============================================================

# Multiplicamos cada componente del vector u por a.
resultado_u = a * u

# Multiplicamos cada componente del vector v por b.
resultado_v = b * v

# Mostramos los resultados de las multiplicaciones.
print("\nMULTIPLICACIONES")
print("a * u =", resultado_u)
print("b * v =", resultado_v)


# ============================================================
# 4. SUMAR LOS VECTORES RESULTANTES
# ============================================================

# Sumamos los vectores escalados para obtener
# la combinación lineal.
w = resultado_u + resultado_v

# Mostramos el vector final.
print("\nCOMBINACIÓN LINEAL")
print("w = a*u + b*v")
print("w =", w)


# ============================================================
# 5. COMPROBAR EL RESULTADO
# ============================================================

# También podemos calcular toda la combinación lineal
# directamente en una sola expresión.
w_directo = a * u + b * v

# Comprobamos que ambos procedimientos producen el mismo
# resultado.
print("\nCOMPROBACIÓN")
print("Resultado directo:", w_directo)
print("¿Los resultados coinciden?",
      np.array_equal(w, w_directo))


# ============================================================
# 6. RESUMEN
# ============================================================

print("\nCONCLUSIÓN")
print("Una combinación lineal multiplica vectores por escalares")
print("y después suma los vectores resultantes.")
print("El vector final es:", w)