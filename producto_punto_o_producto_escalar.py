# ============================================================
# TEMA: PRODUCTO PUNTO O PRODUCTO ESCALAR
# ============================================================
# Objetivo:
# Calcular el producto punto de dos vectores utilizando
# Python y NumPy, y comprobar el resultado manualmente.


# ============================================================
# 1. IMPORTAR LA LIBRERÍA
# ============================================================

# NumPy permite crear vectores y realizar operaciones
# matemáticas de álgebra lineal.
import numpy as np


# ============================================================
# 2. DEFINIR LOS VECTORES
# ============================================================

# Creamos el primer vector con dos componentes.
A = np.array([2, 3])

# Creamos el segundo vector con dos componentes.
B = np.array([4, 5])

# Mostramos los vectores que utilizaremos.
print("VECTOR A:", A)
print("VECTOR B:", B)


# ============================================================
# 3. CALCULAR EL PRODUCTO PUNTO CON NUMPY
# ============================================================

# np.dot() multiplica las componentes correspondientes
# y suma los productos obtenidos.
producto_punto = np.dot(A, B)

# Mostramos el resultado de la operación.
print("\nPRODUCTO PUNTO")
print("A · B =", producto_punto)


# ============================================================
# 4. CALCULAR EL PRODUCTO PUNTO MANUALMENTE
# ============================================================

# Multiplicamos la primera componente de A por la primera
# componente de B.
producto_1 = A[0] * B[0]

# Multiplicamos la segunda componente de A por la segunda
# componente de B.
producto_2 = A[1] * B[1]

# Sumamos los productos de las componentes.
resultado_manual = producto_1 + producto_2

# Mostramos los cálculos intermedios.
print("\nPROCEDIMIENTO MANUAL")
print("Primera multiplicación:", producto_1)
print("Segunda multiplicación:", producto_2)
print("Suma de los productos:", resultado_manual)


# ============================================================
# 5. COMPROBAR LOS RESULTADOS
# ============================================================

# Comparamos el resultado de NumPy con el cálculo manual.
# Si coinciden, la comprobación devuelve True.
print("\nCOMPROBACIÓN")
print(
    "¿Los resultados coinciden?",
    producto_punto == resultado_manual
)


# ============================================================
# 6. PRODUCTO PUNTO EN TRES DIMENSIONES
# ============================================================

# Creamos dos vectores de tres componentes.
C = np.array([1, 2, 3])
D = np.array([4, 5, 6])

# Calculamos el producto punto de ambos vectores.
producto_3d = np.dot(C, D)

# Mostramos los vectores y el resultado.
print("\nPRODUCTO PUNTO EN 3D")
print("Vector C:", C)
print("Vector D:", D)
print("C · D =", producto_3d)

# Cálculo manual:
# 1*4 + 2*5 + 3*6 = 4 + 10 + 18 = 32


# ============================================================
# 7. PRODUCTO PUNTO CON EL OPERADOR @
# ============================================================

# Para dos vectores unidimensionales, el operador @
# también calcula el producto punto.
resultado_arroba = A @ B

# Mostramos el resultado para comparar ambos métodos.
print("\nUSO DEL OPERADOR @")
print("A @ B =", resultado_arroba)


# ============================================================
# 8. CONCLUSIONES
# ============================================================

print("\nCONCLUSIONES")
print("1. El producto punto se calcula componente por componente.")
print("2. Los productos obtenidos se suman.")
print("3. El resultado es un escalar.")
print("4. Los vectores deben tener la misma cantidad de componentes.")
print("5. En NumPy se puede utilizar np.dot() o el operador @.")