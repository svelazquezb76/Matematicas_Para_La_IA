# ============================================================
# TEMA: OPERACIONES CON MATRICES
# ============================================================
# Objetivo:
# 1. Comprobar la igualdad de matrices.
# 2. Realizar suma y resta de matrices.
# 3. Multiplicar una matriz por un escalar.
# 4. Multiplicar dos matrices.
# 5. Verificar las dimensiones de las operaciones.


# ============================================================
# 1. IMPORTAR NUMPY
# ============================================================

# NumPy permite crear matrices y realizar operaciones
# matemáticas de forma eficiente.
import numpy as np


# ============================================================
# 2. DEFINIR DOS MATRICES
# ============================================================

# Creamos la matriz A con dos filas y dos columnas.
A = np.array([
    [1, 2],
    [3, 4]
])

# Creamos la matriz B con el mismo orden que A.
B = np.array([
    [5, 6],
    [7, 8]
])

# Mostramos las matrices originales.
print("MATRIZ A:")
print(A)

print("\nMATRIZ B:")
print(B)


# ============================================================
# 3. IGUALDAD DE MATRICES
# ============================================================

# Creamos una matriz C idéntica a A.
C = np.array([
    [1, 2],
    [3, 4]
])

# np.array_equal verifica que las matrices tengan la misma
# forma y que todos sus elementos correspondientes coincidan.
son_iguales = np.array_equal(A, C)

print("\nIGUALDAD DE MATRICES")
print("¿A y C son iguales?", son_iguales)

# Comparamos A y B.
print("¿A y B son iguales?", np.array_equal(A, B))


# ============================================================
# 4. SUMA DE MATRICES
# ============================================================

# La suma se realiza elemento por elemento.
# Las matrices deben tener el mismo orden.
if A.shape == B.shape:
    suma = A + B

    print("\nSUMA DE MATRICES: A + B")
    print(suma)
else:
    print("No se pueden sumar: tienen órdenes diferentes.")


# ============================================================
# 5. RESTA DE MATRICES
# ============================================================

# Restamos los elementos correspondientes de A y B.
# El orden de la resta determina el signo del resultado.
if A.shape == B.shape:
    resta = A - B

    print("\nRESTA DE MATRICES: A - B")
    print(resta)
else:
    print("No se pueden restar: tienen órdenes diferentes.")


# ============================================================
# 6. MULTIPLICACIÓN POR UN ESCALAR
# ============================================================

# Definimos un escalar, es decir, un número real.
k = 3

# Multiplicamos todos los elementos de A por el escalar.
multiplicacion_escalar = k * A

print("\nMULTIPLICACIÓN POR UN ESCALAR")
print("Escalar:", k)
print("Resultado de 3 * A:")
print(multiplicacion_escalar)


# ============================================================
# 7. MULTIPLICACIÓN DE MATRICES
# ============================================================

# Definimos una matriz A de orden 2x3.
M = np.array([
    [1, 2, 3],
    [4, 5, 6]
])

# Definimos una matriz B de orden 3x2.
N = np.array([
    [7, 8],
    [9, 10],
    [11, 12]
])

print("\nMATRIZ M:")
print(M)
print("Orden de M:", M.shape)

print("\nMATRIZ N:")
print(N)
print("Orden de N:", N.shape)

# Para multiplicar M por N, el número de columnas de M
# debe coincidir con el número de filas de N.
if M.shape[1] == N.shape[0]:

    # El operador @ realiza la multiplicación matricial.
    producto = M @ N

    print("\nPRODUCTO MATRICIAL: M @ N")
    print(producto)

    # El resultado tiene las filas de M y las columnas de N.
    print("Orden del resultado:", producto.shape)

else:
    print("No se pueden multiplicar las matrices.")
    print("Las columnas de M deben coincidir con las filas de N.")


# ============================================================
# 8. COMPROBAR LA MULTIPLICACIÓN MANUALMENTE
# ============================================================

# Calculamos el elemento de la primera fila y primera columna.
# Multiplicamos la primera fila de M por la primera columna de N.
c11 = M[0, 0] * N[0, 0] + \
      M[0, 1] * N[1, 0] + \
      M[0, 2] * N[2, 0]

print("\nCOMPROBACIÓN MANUAL")
print("Elemento de fila 1, columna 1:", c11)

# El resultado debe coincidir con el elemento producto[0, 0].
print("Elemento calculado con NumPy:", producto[0, 0])


# ============================================================
# 9. CONCLUSIONES
# ============================================================

print("\nCONCLUSIONES")
print("1. Dos matrices son iguales si coinciden su orden y elementos.")
print("2. La suma y la resta requieren matrices del mismo orden.")
print("3. El escalar multiplica todos los elementos de una matriz.")
print("4. En la multiplicación matricial deben coincidir las")
print("   columnas de la primera matriz con las filas de la segunda.")
print("5. El operador @ permite realizar el producto matricial.")